create or replace function public.set_guest_reference_number()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.reference_number is null or btrim(new.reference_number) = '' then
    new.reference_number := format(
      'CNPH-GUEST-%s-%s',
      to_char(current_date, 'YYYY'),
      lpad(nextval('public.guest_consultation_reference_seq')::text, 6, '0')
    );
  end if;
  return new;
end;
$$;

create trigger set_guest_reference before insert on public.guest_consultation_requests for each row execute function public.set_guest_reference_number();

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  guest_role_id smallint;
begin
  select id into guest_role_id from public.roles where role_name = 'guest';
  insert into public.users (
    id,
    auth_user_id,
    role_id,
    first_name,
    last_name,
    email,
    mobile_number,
    account_status
  ) values (
    new.id,
    new.id,
    guest_role_id,
    coalesce(new.raw_user_meta_data ->> 'first_name', ''),
    coalesce(new.raw_user_meta_data ->> 'last_name', ''),
    new.email,
    new.phone,
    'active'
  ) on conflict (auth_user_id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_auth_user();

create or replace function public.current_user_id()
returns uuid
language sql
stable
