create policy cnph_guest_documents_owner_insert on storage.objects for insert to authenticated
  with check (bucket_id in ('valid-identification', 'guest-consultation-documents') and public.storage_path_owner(name));
create policy cnph_guest_documents_owner_delete on storage.objects for delete to authenticated
  using (bucket_id in ('valid-identification', 'guest-consultation-documents') and public.storage_path_owner(name));

create policy cnph_patient_documents_care_team_read on storage.objects for select to authenticated
  using (
    bucket_id in ('laboratory-results', 'scanned-medical-results', 'medical-documents', 'prescriptions', 'consultation-attachments')
    and public.can_access_patient_storage(name)
  );
create policy cnph_patient_documents_doctor_insert on storage.objects for insert to authenticated
  with check (
    bucket_id in ('laboratory-results', 'scanned-medical-results', 'medical-documents', 'prescriptions', 'consultation-attachments')
    and public.current_role() = 'doctor'
    and public.can_access_patient_storage(name)
  );

create policy cnph_admin_documents_read on storage.objects for select to authenticated
  using (bucket_id in ('doctor-documents', 'hospital-accreditation-documents') and public.current_role() in ('hospital_admin', 'super_admin'));
create policy cnph_admin_documents_insert on storage.objects for insert to authenticated
  with check (bucket_id in ('doctor-documents', 'hospital-accreditation-documents') and public.current_role() in ('hospital_admin', 'super_admin'));

do $$
declare
  realtime_table text;
begin
  foreach realtime_table in array array[
    'emergency_room_status',
    'hospital_rooms',
    'hospital_beds',
    'doctor_schedules',
    'consultations',
    'chat_messages',
    'notifications'
  ]
  loop
    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = realtime_table
    ) then
      execute format('alter publication supabase_realtime add table public.%I', realtime_table);
    end if;
  end loop;
end;
$$;

commit;
