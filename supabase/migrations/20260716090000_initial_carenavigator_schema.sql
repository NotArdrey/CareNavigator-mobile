create or replace function public.protect_user_privileges()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_role text := public.current_role();
begin
  if (select auth.uid()) is null or actor_role = 'super_admin' then
    return new;
  end if;

  if actor_role = 'hospital_admin' and old.hospital_id = public.current_hospital_id() then
    if new.auth_user_id is distinct from old.auth_user_id
       or new.role_id is distinct from old.role_id
       or new.hospital_id is distinct from old.hospital_id then
      raise exception 'Hospital administrators cannot change identity, role, or hospital assignment directly';
    end if;
    return new;
  end if;

  if old.auth_user_id = (select auth.uid()) then
    if new.auth_user_id is distinct from old.auth_user_id
       or new.role_id is distinct from old.role_id
       or new.hospital_id is distinct from old.hospital_id
       or new.account_status is distinct from old.account_status then
      raise exception 'Role, hospital, identity, and account status are protected';
    end if;
    return new;
  end if;

  raise exception 'Not authorized to update this user';
end;
$$;

create trigger protect_user_privileges_before_update
  before update on public.users
  for each row execute function public.protect_user_privileges();

create or replace function public.nearby_hospitals(
  user_latitude double precision,
  user_longitude double precision,
  radius_km double precision default 100
)
returns table (
  id uuid,
  hospital_name text,
  classification_name text,
  address text,
  latitude numeric,
  longitude numeric,
  contact_number text,
  emergency_contact_number text,
  operating_status public.hospital_operating_status,
  distance_km double precision
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    h.id,
    h.hospital_name,
    hc.classification_name,
    h.address,
    h.latitude,
    h.longitude,
    h.contact_number,
    h.emergency_contact_number,
    h.operating_status,
    6371 * acos(least(1, greatest(-1,
      cos(radians(user_latitude))
      * cos(radians(h.latitude::double precision))
      * cos(radians(h.longitude::double precision) - radians(user_longitude))
      + sin(radians(user_latitude))
      * sin(radians(h.latitude::double precision))
    ))) as distance_km
  from public.hospitals h
  left join public.hospital_classifications hc on hc.id = h.classification_id
  where h.verification_status = 'verified'
    and h.operating_status in ('open', 'limited')
    and h.latitude is not null
    and h.longitude is not null
    and 6371 * acos(least(1, greatest(-1,
      cos(radians(user_latitude))
      * cos(radians(h.latitude::double precision))
      * cos(radians(h.longitude::double precision) - radians(user_longitude))
      + sin(radians(user_latitude))
      * sin(radians(h.latitude::double precision))
    ))) <= radius_km
  order by distance_km;
$$;

