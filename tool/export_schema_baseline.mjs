// Export application DDL and reference rows only; never Auth, patient, or Vault data.
import { sql, env } from './repair_backend.mjs';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const catalog = (await sql(`select jsonb_build_object(
 'tables',(select jsonb_agg(jsonb_build_object('schema',n.nspname,'name',c.relname,'rls',c.relrowsecurity,
   'columns',(select jsonb_agg(jsonb_build_object('name',a.attname,'type',format_type(a.atttypid,a.atttypmod),'notnull',a.attnotnull,
     'default',pg_get_expr(d.adbin,d.adrelid),'identity',a.attidentity,'generated',a.attgenerated) order by a.attnum)
     from pg_attribute a left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum where a.attrelid=c.oid and a.attnum>0 and not a.attisdropped)))
   from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ('public','private') and c.relkind='r'),
 'sequences',(select jsonb_agg(to_jsonb(s)||jsonb_build_object('min_value',s.min_value::text,'max_value',s.max_value::text,'start_value',s.start_value::text)) from pg_sequences s where schemaname in ('public','private') and not exists(select 1 from pg_depend d where d.objid=(quote_ident(s.schemaname)||'.'||quote_ident(s.sequencename))::regclass and d.deptype='i')),
 'enums',(select jsonb_agg(jsonb_build_object('schema',n.nspname,'name',t.typname,'values',(select jsonb_agg(e.enumlabel order by e.enumsortorder) from pg_enum e where e.enumtypid=t.oid)))
   from pg_type t join pg_namespace n on n.oid=t.typnamespace where n.nspname in ('public','private') and t.typtype='e'),
 'functions',(select jsonb_agg(jsonb_build_object('schema',n.nspname,'name',p.proname,'identity',pg_get_function_identity_arguments(p.oid),'definition',pg_get_functiondef(p.oid),
   'grants',(select jsonb_agg(jsonb_build_object('role',case when a.grantee=0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end,'privilege',a.privilege_type)) from aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a)))
   from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname in ('public','private') and p.prokind='f'),
 'constraints',(select jsonb_agg(jsonb_build_object('schema',n.nspname,'table',c.relname,'name',co.conname,'kind',co.contype,'definition',pg_get_constraintdef(co.oid)))
   from pg_constraint co join pg_class c on c.oid=co.conrelid join pg_namespace n on n.oid=c.relnamespace where n.nspname in ('public','private')),
 'indexes',(select jsonb_agg(jsonb_build_object('schema',n.nspname,'definition',pg_get_indexdef(i.indexrelid))) from pg_index i join pg_class c on c.oid=i.indrelid
   join pg_namespace n on n.oid=c.relnamespace where n.nspname in ('public','private') and not exists(select 1 from pg_constraint co where co.conindid=i.indexrelid)),
 'triggers',(select jsonb_agg(jsonb_build_object('schema',n.nspname,'definition',pg_get_triggerdef(t.oid))) from pg_trigger t join pg_class c on c.oid=t.tgrelid
   join pg_namespace n on n.oid=c.relnamespace where not t.tgisinternal and (n.nspname in ('public','private') or (n.nspname='auth' and t.tgfoid in (select p.oid from pg_proc p join pg_namespace pn on pn.oid=p.pronamespace where pn.nspname in ('public','private'))))),
 'policies',(select jsonb_agg(to_jsonb(p)) from pg_policies p where schemaname in ('public','private','storage')),
 'grants',(select jsonb_agg(to_jsonb(g)) from information_schema.role_table_grants g where table_schema in ('public','private'))
) as catalog`))[0].catalog;
// Sequence positions and owners are deployment data, not schema/reference seeds.
for (const sequence of catalog.sequences ?? []) {
  delete sequence.last_value;
  delete sequence.sequenceowner;
}
for (const key of Object.keys(catalog)) {
  catalog[key].sort((a,b)=>JSON.stringify(a).localeCompare(JSON.stringify(b)));
}
if (process.argv.includes('--check')) {
  const expected = JSON.parse(await readFile('supabase/baseline/catalog.json','utf8'));
  // Objects are generated by the same query; sort only deployment-independent sets.
  for (const key of Object.keys(expected)) expected[key].sort((a,b)=>JSON.stringify(a).localeCompare(JSON.stringify(b)));
  if (JSON.stringify(catalog) !== JSON.stringify(expected)) throw new Error('Live schema differs from baseline catalog; reconcile before recording the baseline.');
  console.log('Live application schema matches baseline catalog. No migration applied.');
  process.exit(0);
}
if (process.argv.includes('--catalog-only')) {
  await writeFile('supabase/baseline/catalog.json',JSON.stringify(catalog,null,2));
  console.log('Updated expected catalog for the complete active migration sequence; baseline SQL was not rewritten.');
  process.exit(0);
}
const q = value => '"' + value.replaceAll('"', '""') + '"';
const literal = value => "'" + String(value).replaceAll("'", "''") + "'";
const statements = [
 '-- Sanitized CareNavigator application baseline, 2026-10-11.',
 '-- Apply only to an empty Supabase application schema; platform auth/storage exist first.',
 'create schema if not exists private;',
 'set check_function_bodies = off;',
];
for (const e of catalog.enums) statements.push(`create type ${q(e.schema)}.${q(e.name)} as enum (${e.values.map(literal).join(',')});`);
for (const s of catalog.sequences) statements.push(`create sequence ${q(s.schemaname)}.${q(s.sequencename)} as ${s.data_type} increment ${s.increment_by} minvalue ${s.min_value} maxvalue ${s.max_value} start ${s.start_value} cache ${s.cache_size}${s.cycle ? ' cycle' : ''};`);
for (const t of catalog.tables) {
  const columns = t.columns.map(c => `${q(c.name)} ${c.type}${c.generated ? ' generated always as (' + c.default + ') stored' : c.identity ? ' generated ' + (c.identity === 'a' ? 'always' : 'by default') + ' as identity' : c.default ? ' default ' + c.default : ''}${c.notnull ? ' not null' : ''}`);
  statements.push(`create table ${q(t.schema)}.${q(t.name)} (\n  ${columns.join(',\n  ')}\n);`);
}
for (const f of catalog.functions) statements.push(f.definition.trimEnd().replace(/;?$/, ';'));
// Unique keys precede foreign keys, independent of catalog order.
for (const c of [...catalog.constraints].sort((a,b) => (a.kind === 'f') - (b.kind === 'f'))) statements.push(`alter table ${q(c.schema)}.${q(c.table)} add constraint ${q(c.name)} ${c.definition};`);
for (const i of catalog.indexes ?? []) statements.push(i.definition + ';');
for (const t of catalog.tables) {
  if (t.rls) statements.push(`alter table ${q(t.schema)}.${q(t.name)} enable row level security;`);
  statements.push(`revoke all on table ${q(t.schema)}.${q(t.name)} from public,anon,authenticated;`);
}
for (const g of catalog.grants ?? []) {
  if (['anon','authenticated','service_role'].includes(g.grantee)) statements.push(`grant ${g.privilege_type} on table ${q(g.table_schema)}.${q(g.table_name)} to ${q(g.grantee)};`);
}
for (const f of catalog.functions) {
  const name = `${q(f.schema)}.${q(f.name)}(${f.identity})`;
  statements.push(`revoke all on function ${name} from public,anon,authenticated;`);
  for (const g of f.grants ?? []) if (['PUBLIC','anon','authenticated','service_role'].includes(g.role)) statements.push(`grant ${g.privilege} on function ${name} to ${g.role === 'PUBLIC' ? 'public' : q(g.role)};`);
}
statements.push('grant usage on schema public to anon,authenticated,service_role;',
  'grant usage on schema private to authenticated,service_role;',
  'grant usage,select on all sequences in schema public to authenticated,service_role;');
for (const p of catalog.policies) statements.push(`create policy ${q(p.policyname)} on ${q(p.schemaname)}.${q(p.tablename)} as ${p.permissive} for ${p.cmd} to ${p.roles.map(r => r === 'public' ? 'public' : q(r)).join(',')}${p.qual ? ' using (' + p.qual + ')' : ''}${p.with_check ? ' with check (' + p.with_check + ')' : ''};`);
for (const t of catalog.triggers) statements.push(t.definition + ';');
statements.push('set check_function_bodies = on;');
const baseline = statements.join('\n\n') + '\n';
for (const key of ['SMTP_PASSWORD','NOTIFICATION_DISPATCH_TOKEN','GROQ_API_KEY','ADMIN_BOOTSTRAP_TOKEN','SUPABASE_ACCESS_TOKEN','SUPABASE_DB_PASSWORD']) {
  if (env[key]?.length > 8 && baseline.includes(env[key])) throw new Error('Secret literal found in baseline: ' + key);
}
await mkdir('supabase/baseline', {recursive:true});
await writeFile('supabase/migrations/20261011100000_application_baseline.sql', baseline);
await writeFile('supabase/baseline/catalog.json', JSON.stringify(catalog,null,2));
const seeds = [];
for (const table of ['roles','role_permissions','hospital_classifications','healthcare_service_categories']) {
  const rows = await sql(`select * from public.${q(table)} order by id`);
  for (const row of rows) {
    const names = Object.keys(row);
    seeds.push(`insert into public.${q(table)} (${names.map(q).join(',')}) select ${names.map(k => q(k)).join(',')} from jsonb_populate_record(null::public.${q(table)},${literal(JSON.stringify(row))}::jsonb) on conflict do nothing;`);
  }
  const id = catalog.tables.find(t=>t.schema==='public' && t.name===table).columns.find(c=>c.name==='id');
  if (id.identity || id.default?.includes('nextval')) {
    seeds.push(`select setval(pg_get_serial_sequence('public.${table}','id'),coalesce((select max(id) from public.${q(table)}),1),exists(select 1 from public.${q(table)}));`);
  }
}
await writeFile('supabase/baseline/reference_seed.sql', seeds.join('\n') + '\n');
console.log(JSON.stringify({tables:catalog.tables.length,functions:catalog.functions.length,policies:catalog.policies.length,sha256:createHash('sha256').update(baseline).digest('hex')}));
