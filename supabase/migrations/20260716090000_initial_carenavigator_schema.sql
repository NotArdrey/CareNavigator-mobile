set search_path = ''
as $$
  select u.id from public.users u where u.auth_user_id = (select auth.uid()) limit 1
$$;

create or replace function public.current_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select r.role_name
  from public.users u
  join public.roles r on r.id = u.role_id
  where u.auth_user_id = (select auth.uid())
  limit 1
$$;

